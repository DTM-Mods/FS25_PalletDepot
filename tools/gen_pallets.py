"""Writes the depot pallet vehicles vehicles/depotPallet1000.xml, depotPallet2500.xml and depotPallet5000.xml.

They take every product of both depots (build/products.json); node paths come from the exported i3d files
(tools/build_pallets.py). FedMods products are listed too; without the Fed packs the game logs them as unknown when
a depot pallet is loaded, the base products still work.

    python tools/gen_pallets.py
"""
import json
import os
import sys
import xml.etree.ElementTree as ET

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from finish_i3d import mappings  # noqa: E402
import pallet_layout as L

ROOT = os.path.dirname(HERE)
# size: (width x, length z, height, empty mass kg, max mass kg, price). The game reads both masses in kg
# (Vehicle.lua divides by 1000). 60 kg empty, at most 400 kg full (the NF Marsch goat milk pallet),
# whatever the product, so any loader can lift a full pallet.
PALLETS = {size: (L.WIDTH, L.DEPTH, L.height(size), 60, 400, price)
           for size, price in ((1000, 600), (2500, 1000), (5000, 1500))}
NODES = ["dynamicMountTrigger", "palletVisual", "contentCollision"]


def vehicle(size, fill_types, maps):
    width, length, height, mass, max_mass, price = PALLETS[size]
    name = "depotPallet%d" % size
    layers = ["goodsLayer%02d" % (i + 1) for i in range(L.LAYERS[size])]
    i3d_mappings = "".join('        <i3dMapping id="%s" node="%s"/>\n' % (n, maps[n]) for n in NODES + layers)
    objects = "".join('            <object node="%s" useAsTensionBeltMesh="false"/>\n' % n for n in layers)
    return """<?xml version="1.0" encoding="utf-8" standalone="no" ?>
<!-- Generated by tools/gen_pallets.py, do not edit by hand. -->
<vehicle type="pallet" xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance" xsi:noNamespaceSchemaLocation="../../../../shared/xml/schema/vehicle.xsd">
    <storeData>
        <name>$l10n_storeItem_%(name)s</name>
        <image>store/store_%(name)s.dds</image>
        <price>%(price)d</price>
        <category>pallets</category>
        <brand>NONE</brand>
        <showInStore>false</showInStore>
        <canBeSold>false</canBeSold>
        <financeCategory>OTHER</financeCategory>
    </storeData>

    <base>
        <typeDesc>$l10n_typeDesc_pallet</typeDesc>
        <filename>vehicles/%(name)s.i3d</filename>
        <size width="%(width)g" length="%(length)g" height="%(height)g"/>
        <canBeReset>false</canBeReset>
        <components maxMass="%(maxMass)g">
            <component centerOfMass="0 0.35 0" solverIterationCount="10" mass="%(mass)g"/>
        </components>
        <showInVehicleMenu>false</showInVehicleMenu>
        <mapHotspot available="false"/>
        <input allowed="false"/>
    </base>

    <animations>
        <animation name="fillAnimation">
            <part node="contentCollision" startTime="0" endTime="1" startScale="1 %(minScale)g 1" endScale="1 1 1"/>
        </animation>
    </animations>

    <fillUnit>
        <fillUnitConfigurations>
            <fillUnitConfiguration name="$l10n_configuration_valueDefault">
                <fillUnits removeVehicleIfEmpty="true">
                    <fillUnit unitTextOverride="$l10n_unit_literShort" fillTypes="%(fillTypes)s" capacity="%(size)d" startFillLevel="0" ignoreFillLimit="true">
                        <fillRootNode node="0>"/>
                        <fillLevelAnimation name="fillAnimation" resetOnEmpty="true"/>
                    </fillUnit>
                </fillUnits>
            </fillUnitConfiguration>
        </fillUnitConfigurations>
    </fillUnit>

    <pallet fillUnitIndex="1" node="palletVisual">
        <content>
%(objects)s
        </content>
    </pallet>

    <tensionBeltObject>
        <meshNodes>
            <meshNode node="contentCollision"/>
        </meshNodes>
    </tensionBeltObject>

    <dynamicMount triggerNode="dynamicMountTrigger" triggerForceAcceleration="4" additionalMountDistance="1.1" jointTransY="0.11" jointLimitToRotY="true"/>

    <i3dMappings>
%(mappings)s    </i3dMappings>
</vehicle>
""" % dict(name=name, price=price, width=width, length=length, height=height, maxMass=max_mass, mass=mass,
           fillTypes=" ".join(fill_types), size=size, mappings=i3d_mappings, objects=objects,
           minScale=L.MIN_COLLISION_SCALE)


def main():
    products = json.load(open(os.path.join(ROOT, "build", "products.json"), encoding="utf-8"))
    fill_types = sorted({line["fillType"] for lines in products.values() for line in lines})
    for size in PALLETS:
        i3d = os.path.join(ROOT, "vehicles", "depotPallet%d.i3d" % size)
        maps = mappings(ET.parse(i3d).getroot().find("Scene"))
        required = NODES + ["goodsLayer%02d" % (i + 1) for i in range(L.LAYERS[size])]
        missing = [n for n in required if n not in maps]
        if missing:
            sys.exit("%s is missing nodes %s" % (i3d, missing))
        path = os.path.join(ROOT, "vehicles", "depotPallet%d.xml" % size)
        with open(path, "w", encoding="utf-8", newline="\n") as fh:
            fh.write(vehicle(size, fill_types, maps))
        print("wrote", os.path.relpath(path, ROOT), len(fill_types), "fill types")


if __name__ == "__main__":
    main()
